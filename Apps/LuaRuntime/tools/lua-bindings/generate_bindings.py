#!/usr/bin/env python3
"""Generate Lua capability glue from the bindings/*.toml IDL.

The generated file contains the mechanical part only: argument reading, calling
the exported SDK function, `error_t` to `nil, reason`, handle userdata plumbing
and registration. Functions that need a different Lua shape are marked
`impl = "custom"` and are referenced, not generated.

Usage:
    py generate_bindings.py --idl-dir Apps/LuaRuntime/bindings --output-dir build/generated
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

SCALARS = {
    "bool": "bool",
    "u8": "uint8_t",
    "u16": "uint16_t",
    "u32": "uint32_t",
    "i32": "int32_t",
    "i64": "int64_t",
    "u64": "uint64_t",
    "f64": "double",
}

INTEGER_TYPES = {"u8", "u16", "u32", "i32", "i64", "u64"}


def fail(message):
    print(f"generate_bindings: {message}", file=sys.stderr)
    sys.exit(1)


def parse_args(text):
    args = []
    if not text.strip():
        return args

    for part in text.split(","):
        part = part.strip()
        match = re.fullmatch(r"(\w+)(\?)?\s*:\s*([\w]+)(?:\s*=\s*(.+))?", part)
        if not match:
            fail(f"cannot parse argument {part!r}")
        name, optional, type_name, default = match.groups()
        args.append({
            "name": name,
            "optional": optional is not None,
            "type": type_name,
            "default": default.strip() if default is not None else None,
        })
    return args


def parse_signature(text):
    if "->" not in text:
        fail(f"signature has no '->': {text!r}")
    left, right = text.split("->", 1)
    left = left.strip()

    match = re.fullmatch(r"(?:(\w+):)?(\w+)\((.*)\)", left)
    if not match:
        fail(f"cannot parse signature {text!r}")
    receiver, name, args_text = match.groups()

    returns = [part.strip() for part in right.split("|") if part.strip()]
    if not returns:
        fail(f"signature has no return type: {text!r}")

    return {
        "receiver": receiver,
        "name": name,
        "args": parse_args(args_text),
        "returns": returns,
        "returns_error": len(returns) > 1,
    }


def type_kind(type_name, types):
    return types.get(type_name, {}).get("kind")


def is_handle(type_name, types):
    return type_kind(type_name, types) == "handle"


def is_enum(type_name, types):
    return type_kind(type_name, types) == "enum"


def c_decl(type_name, types, const=False):
    if type_name in SCALARS:
        return SCALARS[type_name]
    if type_name == "string":
        return "const char*"
    if type_name == "Device":
        return "struct Device*"
    if is_handle(type_name, types) or is_enum(type_name, types):
        return types[type_name]["c_type"]
    fail(f"unknown type {type_name!r}")


def argument_expression(argument, index, module, types, receiver_name=None):
    type_name = argument["type"]

    if type_name in INTEGER_TYPES:
        if argument["optional"]:
            default = argument["default"] or "0"
            return f"({c_decl(type_name, types)})luaL_optinteger(state, {index}, {default})"
        return f"({c_decl(type_name, types)})luaL_checkinteger(state, {index})"

    if type_name == "f64":
        if argument["optional"]:
            return f"luaL_optnumber(state, {index}, {argument['default'] or '0'})"
        return f"luaL_checknumber(state, {index})"

    if type_name == "bool":
        return f"(lua_toboolean(state, {index}) != 0)"

    if type_name == "string":
        return f"luaL_checkstring(state, {index})"

    if type_name == "Device":
        return f"lua_bindings_check_device(state, {index})"

    if is_enum(type_name, types):
        c_type = c_decl(type_name, types)
        if argument["optional"]:
            return f"({c_type})luaL_optinteger(state, {index}, {argument['default'] or '0'})"
        return f"({c_type})luaL_checkinteger(state, {index})"

    if is_handle(type_name, types):
        return f"check_{module}_{type_name.lower()}(state, {index})->value"

    fail(f"cannot marshal argument type {type_name!r}")


def push_result(type_name, expression, types):
    if type_name == "bool":
        return f"lua_pushboolean(state, {expression} ? 1 : 0);"
    if type_name in INTEGER_TYPES:
        return f"lua_pushinteger(state, (lua_Integer){expression});"
    if type_name == "f64":
        return f"lua_pushnumber(state, {expression});"
    if type_name == "string":
        return f"lua_pushstring(state, {expression});"
    if is_enum(type_name, types):
        return f"lua_pushinteger(state, (lua_Integer){expression});"
    fail(f"cannot push result type {type_name!r}")


def generate(modules, out_dir):
    lines = []
    lines.append("// Generated by Tools/lua-bindings/generate_bindings.py. Do not edit.")
    lines.append("// Source IDL:")
    for idl in modules:
        lines.append(f"//   {idl['source']}")
    lines.append("")
    lines.append('#include "bindings_private.h"')
    lines.append("")
    includes = []
    for module in modules:
        includes.extend(module["module"].get("includes", []))
    for include in sorted(set(includes)):
        lines.append(f"#include <{include}>")
    lines.append("")
    lines.append("extern \"C\" {")
    lines.append("#include <lauxlib.h>")
    lines.append("}")
    lines.append("")
    lines.append("#include <stdbool.h>")
    lines.append("#include <stdint.h>")
    lines.append("")

    namespace_index = len(lines)
    lines.append("namespace {")
    lines.append("")
    lines.append("int push_error(lua_State* state, error_t error) {")
    lines.append("    lua_pushnil(state);")
    lines.append("    lua_pushstring(state, error_to_string(error));")
    lines.append("    return 2;")
    lines.append("}")
    lines.append("")

    opens = []
    raw_checks = []
    custom_declarations: list[str] = []

    for module in modules:
        name = module["module"]["name"]
        types = module.get("types", {})
        handle_types = {
            type_name: info for type_name, info in types.items() if info.get("kind") == "handle"
        }
        functions = [parse_signature(entry["signature"]) | entry for entry in module.get("function", [])]

        # Handles: struct, check/push, release, gc
        for type_name, type_info in handle_types.items():
            c_type = type_info["c_type"]
            struct_name = f"{name.capitalize()}{type_name}Handle"
            raw_checks.append((f"tactility.{name}.{type_name}", struct_name))
            lines.append(f"struct {struct_name} {{")
            lines.append(f"    {c_type} value;")
            lines.append("    bool released;")
            lines.append("};")
            lines.append("")
            lines.append(f"{struct_name}* check_{name}_{type_name.lower()}(lua_State* state, int index) {{")
            lines.append(f"    auto* handle = static_cast<{struct_name}*>(")
            lines.append(f"        luaL_checkudata(state, index, \"tactility.{name}.{type_name}\"));")
            lines.append("    if (handle->released) {")
            lines.append(f"        luaL_error(state, \"{name}.{type_name} has been released\");")
            lines.append("    }")
            lines.append("    return handle;")
            lines.append("}")
            lines.append("")
            lines.append(f"void push_{name}_{type_name.lower()}(lua_State* state, {c_type} value) {{")
            lines.append(f"    auto* handle = static_cast<{struct_name}*>(")
            lines.append(f"        lua_newuserdatauv(state, sizeof({struct_name}), 0));")
            lines.append("    handle->value = value;")
            lines.append("    handle->released = false;")
            lines.append(f"    luaL_setmetatable(state, \"tactility.{name}.{type_name}\");")
            lines.append("}")
            lines.append("")
            lines.append(f"int lua_{name}_{type_name.lower()}_release(lua_State* state) {{")
            lines.append(f"    auto* handle = static_cast<{struct_name}*>(")
            lines.append(f"        luaL_checkudata(state, 1, \"tactility.{name}.{type_name}\"));")
            lines.append("    if (handle->released) {")
            lines.append("        lua_pushboolean(state, 1);")
            lines.append("        return 1;")
            lines.append("    }")
            lines.append(f"    const error_t error = {type_info['release']}(handle->value);")
            lines.append("    if (error != ERROR_NONE) {")
            lines.append("        return push_error(state, error);")
            lines.append("    }")
            lines.append("    handle->released = true;")
            lines.append("    lua_pushboolean(state, 1);")
            lines.append("    return 1;")
            lines.append("}")
            lines.append("")
            lines.append(f"int lua_{name}_{type_name.lower()}_gc(lua_State* state) {{")
            lines.append(f"    auto* handle = static_cast<{struct_name}*>(")
            lines.append(f"        luaL_checkudata(state, 1, \"tactility.{name}.{type_name}\"));")
            lines.append("    if (!handle->released) {")
            lines.append(f"        {type_info['release']}(handle->value);")
            lines.append("        handle->released = true;")
            lines.append("    }")
            lines.append("    return 0;")
            lines.append("}")
            lines.append("")

        module_functions = []
        method_tables = {type_name: [] for type_name in handle_types}

        for function in functions:
            receiver = function["receiver"]
            if function.get("impl") == "custom":
                target = method_tables[receiver] if receiver else module_functions
                target.append((function["name"], function["c"]))
                declaration = f"int {function['c']}(lua_State* state);"
                if declaration not in custom_declarations:
                    custom_declarations.append(declaration)
                continue

            lua_name = function["name"]
            c_function = function["c"]
            returns = function["returns"]
            success = returns[0]
            c_name = f"lua_{name}_{receiver.lower() + '_' if receiver else ''}{lua_name}"

            lines.append(f"int {c_name}(lua_State* state) {{")
            index = 2 if receiver else 1
            arg_expressions = {}
            for argument in function["args"]:
                arg_expressions[argument["name"]] = argument_expression(argument, index, name, types)
                index += 1

            def build_call_args(include_out):
                call_arguments = []
                if receiver:
                    call_arguments.append(f"check_{name}_{receiver.lower()}(state, 1)->value")

                if function.get("c_args"):
                    for token in function["c_args"]:
                        if token == "out":
                            call_arguments.append("&result")
                        elif token in arg_expressions:
                            call_arguments.append(arg_expressions[token])
                        else:
                            fail(f"{name}.{lua_name}: unknown c_args token {token!r}")
                else:
                    call_arguments.extend(arg_expressions.values())
                    if include_out:
                        call_arguments.append("&result")
                return call_arguments

            if is_handle(success, types):
                call = f"{c_function}({', '.join(build_call_args(False))})"
                lines.append(f"    auto* value = {call};")
                lines.append("    if (value == nullptr) {")
                lines.append("        lua_pushnil(state);")
                null_error = function.get("null_error", f"could not acquire {success}")
                lines.append(f"        lua_pushstring(state, \"{null_error}\");")
                lines.append("        return 2;")
                lines.append("    }")
                lines.append(f"    push_{name}_{success.lower()}(state, value);")
                lines.append("    return 1;")
                lines.append("}")
                lines.append("")
                target = method_tables[receiver] if receiver else module_functions
                target.append((lua_name, c_name))
                continue

            needs_out = success not in ("true", "string")

            if needs_out:
                out_type = c_decl(success, types)
                lines.append(f"    {out_type} result{{}};")
            call_arguments = build_call_args(needs_out)
            lines.append(f"    const error_t error = {c_function}({', '.join(call_arguments)});")

            lines.append("    if (error != ERROR_NONE) {")
            lines.append("        return push_error(state, error);")
            lines.append("    }")
            if needs_out:
                lines.append(f"    {push_result(success, 'result', types)}")
            else:
                lines.append("    lua_pushboolean(state, 1);")
            lines.append("    return 1;")
            lines.append("}")
            lines.append("")

            target = method_tables[receiver] if receiver else module_functions
            target.append((lua_name, c_name))

        # Release is always available on an owned handle.
        for type_name in handle_types:
            method_tables[type_name].append(("release", f"lua_{name}_{type_name.lower()}_release"))

        lines.append(f"const luaL_Reg {name}_functions[] = {{")
        for lua_name, c_name in module_functions:
            lines.append(f"    {{ \"{lua_name}\", {c_name} }},")
        lines.append("    { nullptr, nullptr }")
        lines.append("};")
        lines.append("")

        for type_name, methods in method_tables.items():
            lines.append(f"const luaL_Reg {name}_{type_name.lower()}_methods[] = {{")
            for lua_name, c_name in methods:
                lines.append(f"    {{ \"{lua_name}\", {c_name} }},")
            lines.append("    { nullptr, nullptr }")
            lines.append("};")
            lines.append("")

        lines.append(f"void open_{name}(lua_State* state) {{")
        for type_name in handle_types:
            lines.append(f"    luaL_newmetatable(state, \"tactility.{name}.{type_name}\");")
            lines.append(f"    luaL_newlib(state, {name}_{type_name.lower()}_methods);")
            lines.append("    lua_setfield(state, -2, \"__index\");")
            lines.append(f"    lua_pushcfunction(state, lua_{name}_{type_name.lower()}_gc);")
            lines.append("    lua_setfield(state, -2, \"__gc\");")
            lines.append("    lua_pop(state, 1);")
        lines.append("")
        lines.append("    lua_newtable(state);")
        lines.append(f"    luaL_setfuncs(state, {name}_functions, 0);")
        lines.append(f"    lua_pushinteger(state, {module['module'].get('api', 1)});")
        lines.append("    lua_setfield(state, -2, \"api\");")
        for constant, value in module.get("constants", {}).items():
            lines.append(f"    lua_pushinteger(state, {value});")
            lines.append(f"    lua_setfield(state, -2, \"{constant}\");")
        lines.append(f"    lua_setfield(state, -2, \"{name}\");")
        lines.append("}")
        lines.append("")
        opens.append(f"    open_{name}(state);")

    # Custom implementations live in hand-written C++ files. Declare them outside the
    # anonymous namespace so those definitions have external linkage.
    if custom_declarations:
        lines[namespace_index:namespace_index] = custom_declarations + [""]

    lines.append("} // namespace")
    lines.append("")
    lines.append("void* lua_bindings_raw_pointer(lua_State* state, int index) {")
    lines.append("    if (lua_islightuserdata(state, index)) {")
    lines.append("        return lua_touserdata(state, index);")
    lines.append("    }")
    lines.append("    if (luaL_testudata(state, index, \"tactility.device\") != nullptr) {")
    lines.append("        return lua_bindings_check_device(state, index);")
    lines.append("    }")
    for metatable, struct_name in raw_checks:
        lines.append(f"    if (auto* handle = static_cast<{struct_name}*>(luaL_testudata(state, index, \"{metatable}\"))) {{")
        lines.append("        return handle->value;")
        lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("void lua_bindings_open_generated(lua_State* state) {")
    lines.extend(opens)
    lines.append("}")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "bindings_generated.cpp").write_text("\n".join(lines), encoding="utf-8")
    (out_dir / "bindings_generated.h").write_text(
        "#pragma once\n\n"
        "extern \"C\" {\n"
        "#include <lua.h>\n"
        "}\n\n"
        "void lua_bindings_open_generated(lua_State* state);\n",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser(prog="generate_bindings")
    parser.add_argument("--idl-dir", required=True, help="directory containing *.toml capability definitions")
    parser.add_argument("--output-dir", required=True, help="directory for bindings_generated.{cpp,h}")
    args = parser.parse_args()

    idl_dir = Path(args.idl_dir)
    paths = sorted(idl_dir.glob("*.toml"))
    if not paths:
        fail(f"no *.toml files in {idl_dir}")

    modules = []
    for path in paths:
        with path.open("rb") as file:
            data = tomllib.load(file)
        data["source"] = path.name
        modules.append(data)

    generate(modules, Path(args.output_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
